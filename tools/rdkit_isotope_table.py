"""Generate the isotope mass-shift data used by the Morgan fingerprint.

RDKit's Morgan atom invariant includes
    deltaMass = int(atom.GetMass() - atomicWeight(Z))        (truncated toward 0)
(FingerprintUtil.cpp:252-254). For an isotope, GetMass() is the exact isotope
mass from RDKit's table, or the isotope number itself if the isotope is not in
the table (Atom.cpp:644-655).

So Lean needs, per element:
  * the atomic weight (stored in millionths, exact for RDKit's values), and
  * the known isotopes whose exact mass gives a DIFFERENT shift than the
    isotope number would (all other isotopes follow the "isotope number" rule).

Prints the Lean definitions to paste between the GENERATED markers in
LeanSMILES/Fingerprint/Morgan.lean:
    python tools/rdkit_isotope_table.py
"""
from rdkit import Chem

# Elements covered by the table in LeanSMILES/Fingerprint/Morgan.lean
ZS = [1, 2, 4, 5, 6, 7, 8, 9, 10, 13, 14, 15, 16, 17, 18, 31, 32, 33, 34, 35, 36,
      49, 50, 51, 52, 53, 54]
MAX_ISOTOPE = 400  # RDKit's tables stop well below this for these elements


def trunc(x):
    """C++ static_cast<int>: truncate toward zero."""
    return int(x)


def main():
    pt = Chem.GetPeriodicTable()
    weights = []
    exceptions = []
    for z in ZS:
        w = pt.GetAtomicWeight(z)
        w6 = round(w * 1_000_000)
        assert abs(w6 / 1_000_000 - w) < 1e-9, f"weight of Z={z} not exact in millionths: {w}"
        weights.append((z, w6))
        for iso in range(1, MAX_ISOTOPE + 1):
            mass = pt.GetMassForIsotope(z, iso)
            if mass == 0.0:
                continue  # unknown isotope: Lean uses the isotope number
            exact = trunc(mass - w)
            fallback = trunc(iso - w)
            if exact != fallback:
                exceptions.append((z, iso, exact))
        # self-check: the rule reproduces RDKit's Atom.GetMass() for every isotope
        for iso in range(1, MAX_ISOTOPE + 1):
            a = Chem.Atom(z)
            a.SetIsotope(iso)
            want = trunc(a.GetMass() - w)
            got = next((d for (zz, i, d) in exceptions if zz == z and i == iso), trunc(iso - w))
            assert got == want, (z, iso, got, want)

    print("-- GENERATED by tools/rdkit_isotope_table.py from RDKit "
          f"{Chem.rdBase.rdkitVersion}; do not edit by hand")
    print("/-- Atomic weight in millionths (RDKit `PeriodicTable::getAtomicWeight`). -/")
    print("def atomicWeightMicro : List (Nat × Nat) :=")
    print("  [" + ",\n   ".join(", ".join(f"({z}, {w})" for z, w in weights[k:k + 6])
                                for k in range(0, len(weights), 6)) + "]")
    print()
    print("/-- Known isotopes (element, isotope, mass shift) whose exact mass gives a")
    print("different shift than the isotope number would. -/")
    print("def isotopeShiftExceptions : List (Nat × Nat × Int) :=")
    rows = [f"({z}, {i}, {d})" for z, i, d in exceptions]
    print("  [" + ",\n   ".join(", ".join(rows[k:k + 8]) for k in range(0, len(rows), 8)) + "]")
    print("-- END GENERATED")


if __name__ == "__main__":
    main()
